txt="bhaskar is \"a\" "  #double quotes
print(txt)
txt='it\'s a joke'    #single quote
print(txt)

txt="bhaskar \\ reddy" #backslash
print(txt)

txt="bhaskar\nreddy"   #new line
print(txt)

txt="bhaskat \rsiri"  # carriage return, it moves the cursor to the beginning of the line and overwrites characters.
print(txt)

txt="bhaskar\treddy"  #tab
print(txt)

txt="bhaskar   \breddy" #backspace
print(txt)


